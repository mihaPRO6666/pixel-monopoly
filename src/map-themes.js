export function getMapThemeById(id) {
  return MAP_THEMES.find(t => t.id === id) || MAP_THEMES[0];
}

/**
 * Merges base BOARD_TILES, map theme template, and user custom tile overrides
 */
export function getThemedTileData(baseTile, mapThemeId = 'classic', customTiles = {}) {
  if (!baseTile) return baseTile;
  
  const mapTheme = getMapThemeById(mapThemeId);
  const themeOverride = mapTheme.tiles?.[baseTile.id] || mapTheme.tiles?.[String(baseTile.id)] || {};
  const userOverride = customTiles?.[baseTile.id] || customTiles?.[String(baseTile.id)] || {};

  return {
    ...baseTile,
    name: userOverride.name || themeOverride.name || baseTile.name,
    icon: userOverride.icon || themeOverride.icon || baseTile.icon,
    desc: userOverride.desc !== undefined ? userOverride.desc : (themeOverride.desc !== undefined ? themeOverride.desc : baseTile.desc)
  };
}
